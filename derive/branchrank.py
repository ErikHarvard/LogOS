import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lacore import P, SYN, CON, DIR, CONT, MC, normk, canon, tsize
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "branchgenesis.la")   # a path argument feeds a MUTANT inventory
src = open(SRC, encoding="utf-8").read()

def die(m): print("ERROR: " + m); sys.exit(2)
def parse(e):
    """Px("N") | MC(e) | SYN/CON/DIR/CONT(e)(e) — the constructor syntax branchgenesis.la writes"""
    e = e.strip(); pos = [0]
    def ws():
        while pos[0] < len(e) and e[pos[0]] == " ": pos[0] += 1
    def arg():
        ws()
        if e[pos[0]] != "(": die("expected ( in %r" % e)
        pos[0] += 1; t = term(); ws()
        if e[pos[0]] != ")": die("expected ) in %r" % e)
        pos[0] += 1; return t
    def term():
        ws(); m = re.match(r'Px\("([A-Z]+)"\)', e[pos[0]:])
        if m: pos[0] += m.end(); return P(m.group(1))
        m = re.match(r'(MC|SYN|CONT|CON|DIR)', e[pos[0]:])   # CONT before CON: longest first
        if not m: die("cannot parse %r at %d" % (e, pos[0]))
        pos[0] += m.end(); k = m.group(1)
        if k == "MC": return MC(arg())
        a = arg(); b = arg(); return {"SYN": SYN, "CON": CON, "DIR": DIR, "CONT": CONT}[k](a, b)
    t = term(); ws()
    if pos[0] != len(e): die("trailing text in %r" % e)
    return t

rows = re.findall(r'CONSc\(BRANCH\("([a-z]+)"\)\s*\(BG\((.*?)\)\)\s*\(NL\d((?:\("[a-z]+"\))+)\)\)\(', src)
if len(rows) != 18: die("expected the 18 base branches in BASE_BRANCHES, read %d" % len(rows))
inv = [(n, parse(x), re.findall(r'"([a-z]+)"', regs)) for n, x, regs in rows]
m = re.search(r'^glyph G_DB\s*=\s*SEALc\((.*)\)\s*$', src, re.M)
if not m: die("G_DB not found")
gdb = parse(m.group(1))
m = re.search(r'^glyph C_DB\s*=.*?NL3\("([a-z]+)"\)\("([a-z]+)"\)\("([a-z]+)"\)', src, re.M)
db_regs = list(m.groups()) if m else ["evidential", "topological", "affective"]

B = lambda x: "T" if x else "F"
print("BRANCHRANK inventory read from %s:" % os.path.basename(SRC) + " %d base branches + Δ_B = %d" % (len(inv), len(inv) + 1))

# (1) the closure is infinite
def tower(x, k):
    t = x
    for _ in range(k): t = SYN(x, t)
    return t
inf_ok = all(len({normk(tower(x, k), rb) for k in range(5)}) == 5 for _, x, _ in inv for rb in (True, False))
print("BRANCHRANK (1) closure under ⊕ ⊗ ↻ is INFINITE: for every interface x, x ⊗(x,x) ⊗(x,⊗(x,x)) … are 5 NORMK-distinct forms at depth 4 (both registers):%s"
      " ⇒ a finite count can only be a RANK (a minimal generating set — the codex's own L8 audit criterion, App B :4294)" % B(inf_ok))

# (2) branch glyphs: head ⊂ (▷ for Δ_B) — never produced by ⊕ ⊗ ↻
