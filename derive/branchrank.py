    regen = {n: generated(x, irr, rb)[0] for n, x in allx if n in der}
    bad = [n for n, w in regen.items() if w is None]
    print("BRANCHRANK     the %d irreducibles alone regenerate every derived branch (the minimal generating set is UNIQUE):%s%s"
          % (len(irr), B(not bad), "" if not bad else " — NOT regenerated: " + ", ".join(bad)))

